-- Final Whistle scores table
-- Run this in Supabase Dashboard -> SQL Editor -> New query.

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  score integer not null check (score >= 0 and score <= 10),
  created_at timestamptz not null default now()
);

alter table public.scores enable row level security;

drop policy if exists "Players can read their own scores" on public.scores;
create policy "Players can read their own scores"
on public.scores for select
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Players can insert their own scores" on public.scores;
create policy "Players can insert their own scores"
on public.scores for insert
to authenticated
with check (auth.uid() = user_id);

create index if not exists scores_score_created_at_idx
on public.scores (score desc, created_at desc);

create index if not exists scores_user_id_idx
on public.scores (user_id);
